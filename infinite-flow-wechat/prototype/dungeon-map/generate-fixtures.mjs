/** Export explicit visual demo snapshots through production projection. No game state is written. */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { createInitialState, enterDungeon, DUNGEON_ORDER, DUNGEONS } from '../../packages/core/dist/game.js';
import { buildGameViewModel } from '../../packages/presentation/dist/index.js';

const definitions = [
  { id:'demon_tower_1', source:'demon-tower.ts', label:'第一章 · 妖塔一层', scene:'demon_tower_1', current:'cracked_portal', cleared:['fog_lesser_demon','blood_rune_trap'], discovered:['watch_post_cache','upper_fog_patrol','loose_tile_trap','broken_sigil_reward','left_watch_trap','fog_lesser_demon','blood_rune_trap','cracked_portal','demon_bone_cache'] },
  { id:'temporal_observatory', source:'temporal-observatory.ts', label:'第八章 · 时序观测庭', scene:'temporal_observatory', current:'calibration_bridge', cleared:['temporal_gate','clockwork_scout','zero_meridian'], discovered:['past_calibration_anchor','epoch_sentinel_alpha','entry_chronometer','past_shortcut_foyer','erased_patrol','field_observation_deck','temporal_gate','clockwork_scout','zero_meridian','calibration_bridge','future_supply','future_shortcut_foyer','accelerated_patrol'] },
  { id:'panopticon_city', source:'panopticon-city.ts', label:'第十九章 · 天幕监察城', scene:'panopticon_city', current:'south_blind_relay', cleared:['panopticon_gate','watchglass_cache','exposure_double_patrol'], discovered:['blindline_archive','north_blind_relay','upper_entry','all_sight_lock','blindspot_theater','scan_lattice_trap','central_blind_relay','panopticon_gate','watchglass_cache','exposure_double_patrol','south_blind_relay','lower_entry','matte_supply','blind_angle_trap','inverse_observation_stage','sweep_sentinel'] }
];
const fixtures=[];
for(const def of definitions){
  const initial=createInitialState();
  const entry=enterDungeon({...initial, completedDungeonIds:[...DUNGEON_ORDER]},def.id,'standard',undefined,{flowVersion:2,hiddenTaskSeed:0x12345678});
  if(!entry.run) throw new Error(`Entry unavailable: ${def.id}`);
  const states=[
    { id:'exploring', label:'途中探索', current:def.current, cleared:def.cleared, discovered:def.discovered },
    { id:'arrival', label:'初入副本', current:entry.run.currentNodeId, cleared:[], discovered:[entry.run.currentNodeId] }
  ];
  const samples=states.map(sample=>{
    const state={...entry,phase:'explore',combat:undefined,run:{...entry.run,currentNodeId:sample.current,clearedNodeIds:sample.cleared,discoveredNodeIds:sample.discovered,lawState:{...entry.run.lawState,clearedNodeIds:sample.cleared}}};
    const model=buildGameViewModel(state,{});
    const detail=model.sections[1].detail;
    if(detail.kind!=='explore')throw new Error(`Missing explore projection: ${def.id}`);
    const map=detail.map;
    // Only edges whose two endpoints are already known are exported to the UI.
    // Standard runs use Manhattan-adjacent cells; no inferno topology is fabricated.
    const known=map.nodes.filter(n=>n.state!=='fogged');
    const edges=known.flatMap((a,i)=>known.slice(i+1).filter(b=>Math.abs(a.x-b.x)+Math.abs(a.y-b.y)===1).map(b=>[a.cellId,b.cellId]));
    for(const node of map.nodes.filter(n=>n.state==='fogged')){
      if(node.nodeId!==undefined||node.nodeType!=='unknown'||node.title!=='未知区域')throw new Error('Fog identity leaked');
    }
    return {id:sample.id,label:sample.label,current:detail.currentNode,map,edges};
  });
  const dungeon=DUNGEONS[def.id];
  fixtures.push({id:def.id,label:def.label,scene:def.scene,name:dungeon.name,tier:dungeon.tier,source:`packages/core/src/level-data/${def.source}`,samples});
}
const output={
  kind:'html-visual-demo',
  notice:'演示状态由指定当前位置、已清理和已发现集合构造；拓扑、名称和移动禁用原因由现有代码投影。不是存档、通关记录或新增移动能力。',
  topologyRule:'standard: Manhattan distance 1; known endpoints only. Deep/inferno is not part of this prototype.',
  projectionSource:'packages/presentation/src/view-model.ts: getPhysicalAdjacentIds / getMapNodeState / buildMap',
  chapters:fixtures
};
const serialized=JSON.stringify(output,null,2);
await writeFile(new URL('fixtures.json',import.meta.url),serialized+'\n');
// Classic script data keeps the prototype usable when opened directly from disk.
await writeFile(new URL('fixtures.js',import.meta.url),'// Generated by generate-fixtures.mjs; do not edit.\nconst dungeonMapFixtures = '+serialized+';\n');
console.log(`Exported ${fixtures.length} chapters, ${fixtures.reduce((n,c)=>n+c.samples.length,0)} snapshots to ${fileURLToPath(new URL('.',import.meta.url))} (fixtures.json and fixtures.js)`);
